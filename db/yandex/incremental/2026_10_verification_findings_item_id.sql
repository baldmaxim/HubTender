-- Проверка данных: строка расчёта у сохранённой находки (verification_findings.item_id).
--
-- Бот замечаний строит у каждой находки ссылку «к строке». Позиция есть только у
-- находок по позиции и по строке; у правил по материалу справочника (P, B и др.)
-- позиции нет, хотя движок проверки уже вычисляет строку (Finding.ItemID — колонка
-- item_id правила). Теперь она сохраняется, и ссылка ведёт на эту строку.
--
-- Инварианты:
--   * столбец необязательный: старые находки остаются с NULL и получают значение
--     при следующем прогоне проверки; бот для них использует прежний фолбэк;
--   * без FK и индекса — столбец только для ссылки, строка может быть удалена;
--   * миграция идемпотентна.
--
-- На production применена 22.10.2026 (до деплоя бэкенда).
-- Порядок: эта миграция → бэкенд → фронтенд.

BEGIN;

ALTER TABLE public.verification_findings ADD COLUMN IF NOT EXISTS item_id uuid;

COMMENT ON COLUMN public.verification_findings.item_id IS
    'Строка расчёта, к которой ведёт ссылка «к строке»: у находки по строке — она сама, у правил по позиции/материалу — колонка item_id правила; NULL — строки нет.';

COMMIT;
