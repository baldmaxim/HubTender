-- Конвейер проверки расчёта: фоновый прогон проверки данных после пересчёта.
--
-- Бэкенд после каждого успешного пересчёта тендера (с дебаунсом в минуту)
-- прогоняет каталог правил и сохраняет находки — история «что открылось/закрылось»
-- копится, даже если страницу «Проверка данных» никто не открывал. Такие прогоны
-- пишутся с trigger_source = 'auto'.
--
-- Старые прогоны бэкенд удаляет сам (старше 30 дней, кроме последней отметки
-- «Проверка завершена» по тендеру).
--
-- Идемпотентно: повторный запуск безопасен. Бэкенд, выкаченный раньше миграции,
-- не ломается: фоновый прогон не сохранится (предупреждение в логе).
--
-- ВНИМАНИЕ: НЕ применять к production вручную из кода. Применяет пользователь.
-- Порядок выкатки: миграция → бэкенд.

BEGIN;

ALTER TABLE public.verification_runs
    DROP CONSTRAINT IF EXISTS verification_runs_trigger_check;
ALTER TABLE public.verification_runs
    ADD CONSTRAINT verification_runs_trigger_check
    CHECK (trigger_source IN ('checkpoint', 'view', 'api', 'auto'));

COMMIT;
