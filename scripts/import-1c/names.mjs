// Сопоставление наименований 1С со справочником HUBTender по канонической
// форме: «Плита ПДП (3,0х1,75х0,17м)» и «плита пдп 3.0x1.75x0.17 м» — одно и то же.
// Ключ = вид (работа/материал) + каноническое имя + единица. Совпал — берём
// существующее наименование, нет — создаём новое (самое частое написание из 1С).

// Латинские буквы, неотличимые от кириллических, — к кириллице (только для ключа).
const HOMOGLYPHS = { a: 'а', b: 'в', c: 'с', e: 'е', h: 'н', k: 'к', m: 'м', o: 'о', p: 'р', t: 'т', x: 'х', y: 'у' };
const TAIL_PHRASES = /\s*(или\s+(аналог|эквивалент)\w*|аналог)\.?\s*$/u;
const UNIT_TAIL = /\s*\((шт|м|м2|м3|кг|т|тн|л|компл|м\.?п\.?|пог\.?\s?м|упак|лист)\.?\)\s*$/u;

/** Каноническая форма наименования для сравнения. */
export const canonName = (raw) => {
  let s = String(raw ?? '').toLowerCase().replace(/ё/g, 'е');
  s = s.replace(/[«»"“”„'`]/g, ' ');
  for (let i = 0; i < 2; i += 1) s = s.replace(TAIL_PHRASES, '').replace(UNIT_TAIL, '');
  s = s.replace(/(\d)[,.](\d)/g, "$1.$2"); // 6,0 → 6.0 (без пробелов: «32, 40» — список)
  s = s.replace(/(\d)\s*[xх*×]\s*(?=\d)/g, '$1x'); // 6х2,5 → 6x2.5
  s = s.replace(/[a-z]/g, (ch) => HOMOGLYPHS[ch] ?? ch);
  s = s.replace(/(\d)х(?=\d)/g, '$1x');
  s = s.replace(/(\d)(?=[а-яa-wyz])/g, '$1 ').replace(/([а-яa-wyz])(?=\d)/g, '$1 '); // 0.17м → 0.17 м
  s = s.replace(/[^a-zа-я0-9.x]+/g, ' ').replace(/(^|\s)\.+|\.+(?=\s|$)/g, ' ');
  return s.replace(/\s+/g, ' ').trim();
};

/** Ключ наименования: вид|слова канонического имени по алфавиту|единица (порядок слов не важен). */
export const canonKey = (kind, name, unit) => {
  const words = canonName(name).split(' ').filter(Boolean).sort().join(' ');
  return `${kind}|${words}|${String(unit ?? '').trim().toLowerCase()}`;
};
