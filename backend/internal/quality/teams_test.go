package quality

import "testing"

func TestClassifyTeam(t *testing.T) {
	cases := []struct {
		name    string
		headers []string
		own     string
		want    string
		ok      bool
	}{
		{"кровля", []string{"Деформационный шов в примыкании к стене", "Секция 1", "Устройство кровли высотной части", "Устройство кровли"}, "", TeamGeneral, true},
		{"электрика", []string{"Электрические и слаботочные инженерные системы", "Внутренние инженерные системы корпусов", "Инженерные системы"}, "", TeamElectric, true},
		{"механика", []string{"Механические инженерные системы", "Внутренние инженерные системы корпусов", "Инженерные системы"}, "", TeamHVAC, true},
		{"электроснабжение", []string{"Электроснабжение и освещение", "Внутренние инженерные системы надземной части", "Комплекс работ надземной части", "КОРПУС 2.1"}, "", TeamElectric, true},
		{"фасады выше слабого", []string{"Надземная часть", "Фасады (включая все светопрозрачные конструкции)"}, "", TeamFacade, true},
		{"благоустройство", []string{"Устройство подстилающих слоев", "Твердые покрытия", "Благоустройство и наружное освещение"}, "", TeamGeneral, true},
		{"отделка", []string{"Отделка по дизайн-проекту помещений 1-го этажа", "Внутренняя отделка МОП по дизайн-проекту", "Внутренние отделочные работы"}, "", TeamFinish, true},
		{"двери", []string{"Монтаж дверей надземной части", "Заполнение дверных проемов", "Отделочные работы"}, "", TeamGeneral, true},
		{"водоснабжение", []string{"Сети водоснабжения (по каждому корпусу)"}, "", TeamHVAC, true},
		{"связь", []string{"Системы связи"}, "", TeamElectric, true},
		{"автоматика", []string{"Устройство систем противопожарной автоматики"}, "", TeamElectric, true},
		{"временное электроснабжение", []string{"Устройство временного электроснабжения"}, "", TeamGeneral, true},
		{"временное освещение", []string{"Монтаж прожекторов временного освещения"}, "", TeamGeneral, true},
		{"ограждающие", []string{"Устройство наружных ограждающих конструкций"}, "", TeamFacade, true},
		{"монолит", []string{"Монолитные работы"}, "", TeamGeneral, true},
		{"витражи", []string{"Устройство витражей"}, "", TeamFacade, true},
		{"технология", []string{"Технологические решения автостоянки"}, "", TeamGeneral, true},
		{"по имени позиции", []string{"Наружные сети:"}, "Наружные сети водоснабжения", TeamHVAC, true},
		{"не распознано", []string{"Прочее"}, "ЗИП", "", false},
		{"пусто", nil, "", "", false},
		{"теплоизоляция", []string{"Теплоизоляция перекрытий"}, "", TeamGeneral, true},
		{"токен ЭО", []string{"Монтаж внутренних систем ЭО"}, "", TeamElectric, true},
		{"прочие механические системы", []string{"Прочие механические системы", "Внутренние инженерные системы корпусов", "Инженерные системы"}, "", TeamHVAC, true},
		{"механизированная разработка — не ОВиВК", []string{"Разработка грунта механизированным способом"}, "", TeamGeneral, true},
		{"теплоизол длиннее теплов", []string{"Теплоизоляция"}, "", TeamGeneral, true},
		{"ё как е", []string{"Подъёмник"}, "", TeamGeneral, true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, ok := ClassifyTeam(c.headers, c.own)
			if got != c.want || ok != c.ok {
				t.Fatalf("ClassifyTeam(%q, %q) = %q, %v; ждали %q, %v", c.headers, c.own, got, ok, c.want, c.ok)
			}
		})
	}
}
